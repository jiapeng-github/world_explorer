class CountryMapProfile {
  const CountryMapProfile({
    required this.id,
    required this.name,
    required this.waterAsset,
    required this.features,
    required this.view,
    required this.featuredPlaces,
    required this.searchPrompt,
    required this.searchExample,
    required this.waterCredit,
    this.defaultPlace,
    this.areaAsset,
    this.biomeAsset,
    this.waterLabel = '河流',
    this.placesLabel = '地标',
    this.maxScale = 10,
    this.relief,
    this.detailAsset,
    this.focusViews = const {},
  });

  final String id, name, waterAsset, searchPrompt, searchExample, waterCredit;
  final List<CountryMapFeature> features;
  final Set<String> featuredPlaces;
  final ({double west, double south, double east, double north}) view;
  final String? defaultPlace;
  final String? areaAsset;
  final String? biomeAsset;
  final String waterLabel, placesLabel;
  final double maxScale;
  final CountryMapRelief? relief;
  final String? detailAsset;
  final Map<String, ({double west, double south, double east, double north})>
  focusViews;

  Rect get bounds => Rect.fromPoints(
    project(view.north, view.west),
    project(view.south, view.east),
  );
}

/// NASA GIBS assets use geographic WGS84 bounds, with north at the top.
class CountryMapRelief {
  const CountryMapRelief(
    this.asset,
    this.west,
    this.south,
    this.east,
    this.north,
  );
  final String asset;
  final double west, south, east, north;
  Rect get bounds =>
      Rect.fromPoints(project(north, west), project(south, east));
}

