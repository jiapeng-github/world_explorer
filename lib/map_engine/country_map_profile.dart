/// Natural-feature anchors are label/observation points, not geographic extents.
class CountryMapFeature {
  const CountryMapFeature(
    this.id,
    this.name,
    this.latitude,
    this.longitude,
    this.description,
    this.articleId,
    this.mediaId, {
    this.river = false,
    this.area = false,
    this.ecology = false,
    this.color = const Color(0xff24725b),
  });
  final String id, name, description, articleId, mediaId;
  final double latitude, longitude;
  final bool river, area;
  final bool ecology;
  final Color color;
  Offset get point => project(latitude, longitude);
}

